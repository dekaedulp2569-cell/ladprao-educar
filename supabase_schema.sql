CREATE TABLE user_profiles (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    full_name VARCHAR(255) NOT NULL,
    nickname VARCHAR(100),
    position VARCHAR(255) NOT NULL,
    department VARCHAR(255) NOT NULL,
    phone VARCHAR(50),
    line_user_id VARCHAR(255) UNIQUE,
    role VARCHAR(50) NOT NULL CHECK (role IN ('admin', 'head_of_dept', 'driver', 'requester')),
    driver_dept_type VARCHAR(20) CHECK (driver_dept_type IN ('education', 'other')),
    status VARCHAR(20) DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE car_requests (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    requester_auth_user_id UUID,
    request_date DATE NOT NULL DEFAULT ((NOW() AT TIME ZONE 'Asia/Bangkok')::date),
    doc_type VARCHAR(20) CHECK (doc_type IN ('school_letter', 'dept_form')),
    doc_number VARCHAR(100) NOT NULL,
    requester_name VARCHAR(255) NOT NULL,
    requester_position VARCHAR(255) NOT NULL,
    requester_department VARCHAR(255) NOT NULL,
    phone VARCHAR(50),
    pickup_location TEXT DEFAULT 'สำนักงานเขตลาดพร้าว',
    destination TEXT NOT NULL,
    destination_province VARCHAR(100) DEFAULT 'กรุงเทพมหานคร',
    passenger_name TEXT,
    passenger_phone TEXT,
    passenger_count INT DEFAULT 1,
    purpose TEXT,
    start_datetime TIMESTAMPTZ NOT NULL,
    end_datetime TIMESTAMPTZ NOT NULL,
    assigned_car_id UUID REFERENCES cars(id) ON DELETE SET NULL,
    external_car_info VARCHAR(255),
    assigned_driver_id UUID REFERENCES user_profiles(id) ON DELETE SET NULL,
    external_driver_name VARCHAR(255),
    is_out_of_hours BOOLEAN DEFAULT FALSE,
    is_out_of_bkk BOOLEAN DEFAULT FALSE,
    is_weekend BOOLEAN DEFAULT FALSE,
    is_public_holiday BOOLEAN DEFAULT FALSE,
    approval_type VARCHAR(50) CHECK (approval_type IN ('head_of_dept', 'district_director')),
    status VARCHAR(20) DEFAULT 'pending' CHECK (status IN ('pending', 'tentative', 'approved', 'rejected', 'cancelled')),
    director_approval_status VARCHAR(20) DEFAULT 'not_required' CHECK (director_approval_status IN ('not_required', 'pending', 'approved', 'rejected')),
    related_line_user_ids TEXT[] DEFAULT '{}',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);
-- ตั้งค่าการแจ้งเตือนต่องาน (reminder levels)
-- คำขอแต่ละงานเลือกได้ว่าจะแจ้งซ้ำก่อนออกรถฉบับไหนบ้าง (งานประจำแจ้งน้อย / งานสำคัญแจ้งครบ)
--   '60'           = เตือนคนขับ 60 นาทีก่อนออกรถ (ใบสั่งงานฉบับเต็ม)
--   '30'           = เตือนคนขับ 30 นาทีก่อนออกรถ
--   '10'           = เตือนคนขับ 10 นาทีก่อนออกรถ
--   'passenger_10' = เตือนผู้ขอ/ผู้เดินทาง 10 นาทีก่อนออกรถ
--
-- ค่าเริ่มต้น = แจ้งครบทุกฉบับ (เหมือนระบบเดิม) — คำขอเก่าทั้งหมดได้ค่านี้โดยอัตโนมัติ
-- Edge Function: trip-reminders จะข้ามฉบับที่ไม่ได้อยู่ในรายการของงานนั้น

alter table public.car_requests
  add column if not exists reminder_levels text[] not null default '{60,30,10,passenger_10}';

comment on column public.car_requests.reminder_levels is
  'ระดับการแจ้งเตือนก่อนออกรถที่เปิดใช้ของงานนี้ (60, 30, 10, passenger_10) — ตั้งตอนบันทึกการจัดสรร';
